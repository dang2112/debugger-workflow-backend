"""Adapter for the cloned function-level SBFL engine in tools/sbfl.

The engine runs in the target Python environment, outside the API process.
Only workspace-relative source/test paths are accepted; no shell is used.
"""
from __future__ import annotations

import json
import hashlib
import os
from pathlib import Path
import signal
import subprocess
import sys
import time
from uuid import uuid4
from typing import Callable

from pydantic import BaseModel, Field
from orchestrator.preparation import RunSBFLArguments

from orchestrator.actions import ReadFileArguments
from orchestrator.state import EvidenceItem, EvidenceType, FaultCandidate, FaultLocalizationResult


ENGINE_SOURCE = Path(__file__).resolve().parent / "sbfl" / "src"


class SBFLRunResult(BaseModel):
    run_id: str
    status: str
    source_root: str
    total_tests: int
    total_failing: int
    excluded_tests: int
    pytest_exit_code: int
    localization: FaultLocalizationResult
    recommended_files: list[str]
    source_files: dict[str, dict] = Field(default_factory=dict)
    test_outcomes: list[dict] = Field(default_factory=list)
    source_basis: str = "workspace files on disk; unsaved editor changes are not executed"


class SBFLService:
    def __init__(self, artifact_directory: str | Path, python_executable: str | None = None):
        self.artifact_directory = Path(artifact_directory).resolve()
        self.python = python_executable or os.environ.get("SBFL_PYTHON_EXECUTABLE", sys.executable)

    @staticmethod
    def workspace_path(workspace: Path, relative: str, *, directory: bool = False) -> Path:
        if relative != ".":
            relative = ReadFileArguments(path=relative).path
        path = (workspace / relative).resolve()
        if not path.is_relative_to(workspace):
            raise ValueError("Path escapes the session workspace")
        if directory and not path.is_dir():
            raise ValueError(f"Directory not found: {relative}")
        return path

    def _directory(self, run_id: str) -> Path:
        # Run IDs are generated by this adapter, never filesystem paths from the model.
        if len(run_id) != 32 or any(c not in "0123456789abcdef" for c in run_id):
            raise ValueError("Invalid SBFL run ID")
        return self.artifact_directory / run_id

    def _environment(self, workspace: Path) -> dict[str, str]:
        env = os.environ.copy()
        env["PYTHONPATH"] = os.pathsep.join([
            str(workspace / "src"), str(workspace), str(ENGINE_SOURCE),
            env.get("PYTHONPATH", ""),
        ])
        # Do not let inherited pytest flags redirect output, enable xdist, or skip tests.
        env.pop("PYTEST_ADDOPTS", None)
        env.pop("PYTEST_PLUGINS", None)
        env["PYTHONIOENCODING"] = "utf-8"
        return env

    @staticmethod
    def _stop_process(process) -> None:
        if os.name == "nt":
            subprocess.run(["taskkill", "/PID", str(process.pid), "/T", "/F"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
        else:
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        if process.poll() is None:
            process.kill()
        process.wait()

    def _execute(self, args: list[str], workspace: Path, env: dict, log: Path, timeout: float,
                 is_cancelled: Callable[[], bool] | None = None) -> int:
        if timeout <= 0:
            raise TimeoutError("SBFL exceeded its wall-clock timeout")
        with log.open("w", encoding="utf-8") as output:
            process = subprocess.Popen(
                [self.python, *args], cwd=workspace, env=env, stdout=output,
                stderr=subprocess.STDOUT, shell=False,
                start_new_session=os.name != "nt",
                creationflags=subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0,
            )
            deadline = time.monotonic() + timeout
            try:
                while True:
                    if is_cancelled and is_cancelled():
                        raise RuntimeError("SBFL session cancelled")
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        raise TimeoutError("SBFL exceeded its wall-clock timeout")
                    try:
                        return process.wait(timeout=min(0.25, remaining))
                    except subprocess.TimeoutExpired:
                        continue
            except BaseException:
                self._stop_process(process)
                raise

    def run(self, workspace_path: str | None, arguments: RunSBFLArguments,
            is_cancelled: Callable[[], bool] | None = None) -> SBFLRunResult:
        if not workspace_path:
            raise ValueError("SBFL requires a backend-accessible context.workspace_path")
        workspace = Path(workspace_path).resolve()
        if not workspace.is_dir():
            raise ValueError("Session workspace does not exist on the backend")
        if not (ENGINE_SOURCE / "sbfl" / "pytest_plugin.py").is_file():
            raise ValueError("SBFL checkout missing: expected tools/sbfl/src/sbfl")
        source = self.workspace_path(workspace, arguments.source_root, directory=True)
        tests = arguments.test_ids or ["tests"]
        for test in tests:
            self.workspace_path(workspace, test.split("::", 1)[0])
        run_id = uuid4().hex
        directory = self._directory(run_id)
        directory.mkdir(parents=True)
        evidence_path = directory / "evidence.json"
        ranking_path = directory / "ranking.json"
        env = self._environment(workspace)
        # Cloned/copied .pyc files can retain another checkout's co_filename,
        # making the tracer miss every function. Use fresh bytecode per run.
        env["PYTHONPYCACHEPREFIX"] = str(directory / "pycache")
        env.update(SBFL_SOURCE_ROOT=str(source), SBFL_OUTPUT=str(evidence_path),
                   SBFL_EXCLUDE_INTERNET="1" if arguments.exclude_internet else "0",
                   SBFL_TEST_TIMEOUT=str(arguments.test_timeout_seconds))
        command = ["-m", "pytest", "-o", "addopts=", "-p", "sbfl.pytest_plugin", "-q", "--", *tests]
        started = time.monotonic()
        code = self._execute(command, workspace, env, directory / "pytest.log", arguments.timeout_seconds, is_cancelled)
        # 1 means the target's tests failed, which is useful SBFL evidence.
        if code not in (0, 1) or not evidence_path.is_file():
            raise RuntimeError(f"SBFL collection failed (pytest exit {code}); see {directory / 'pytest.log'}")
        rank_code = self._execute(
            ["-m", "sbfl.cli", "rank", "--evidence", str(evidence_path), "--output", str(ranking_path)],
            workspace, env, directory / "rank.log",
            arguments.timeout_seconds - (time.monotonic() - started),
            is_cancelled,
        )
        if rank_code not in (0, 2) or not ranking_path.is_file():
            raise RuntimeError("SBFL ranking did not produce a valid artifact")
        ranking = json.loads(ranking_path.read_text(encoding="utf-8"))
        evidence = json.loads(evidence_path.read_text(encoding="utf-8"))
        candidates = []
        for item in ranking.get("ranking", [])[:arguments.top_k]:
            # Engine paths are relative to source_root.parent, not the workspace.
            relative_file, symbol_line = item["function_id"].split("::", 1)
            absolute_file = (source.parent / relative_file).resolve()
            if not absolute_file.is_relative_to(source) or not absolute_file.is_relative_to(workspace):
                raise ValueError("SBFL artifact contains a file outside the source root")
            symbol, line = symbol_line.rsplit("@", 1)
            candidates.append(FaultCandidate(
                path=absolute_file.relative_to(workspace).as_posix(), function=symbol,
                suspiciousness=item["score"], line_start=int(line), metadata=item,
            ))
        recommended = list(dict.fromkeys(c.path for c in candidates if c.suspiciousness > 0))[:3]
        eligible = [t for t in evidence["tests"] if not t.get("excluded_from_ranking")
                    and t.get("outcome") in ("passed", "failed")]
        summary = {"run_id": run_id, "total_tests": len(eligible),
                   "total_failing": sum(t["outcome"] == "failed" for t in eligible),
                   "excluded_tests": sum(bool(t.get("excluded_from_ranking")) for t in evidence["tests"])}
        result = SBFLRunResult(
            **summary, source_root=source.relative_to(workspace).as_posix(),
            status=ranking.get("status", "ranked" if candidates else "no_covered_functions"), pytest_exit_code=code,
            localization=FaultLocalizationResult(candidates=candidates, evidence=[EvidenceItem(
                type=EvidenceType.SBFL_RESULT, source="sbfl.ochiai",
                content=json.dumps(summary), metadata={"granularity": "function", "source_basis": "disk"},
            )]), recommended_files=recommended,
            source_files={path: {"sha256": hashlib.sha256((workspace / path).read_bytes()).hexdigest(),
                                 "captured": "after_collection", "isolated": False} for path in recommended},
            test_outcomes=[{key: t.get(key) for key in ("nodeid", "outcome", "excluded_from_ranking", "exclusion_reason")}
                           for t in sorted(evidence["tests"], key=lambda t: t.get("outcome") != "failed")[:100]],
        )
        (directory / "result.json").write_text(result.model_dump_json(indent=2), encoding="utf-8")
        return result

    def list_tests(self, run_id: str, offset: int = 0, limit: int = 50) -> dict:
        evidence = json.loads((self._directory(run_id) / "evidence.json").read_text(encoding="utf-8"))
        tests = evidence["tests"]
        return {"run_id": run_id, "total": len(tests), "tests": [
            {k: test.get(k) for k in ("nodeid", "outcome", "excluded_from_ranking", "exclusion_reason")}
            for test in tests[offset:offset + limit]
        ]}

    def trace(self, run_id: str, test_id: str, offset: int = 0, limit: int = 10) -> dict:
        evidence = json.loads((self._directory(run_id) / "evidence.json").read_text(encoding="utf-8"))
        test = next((t for t in evidence["tests"] if t["nodeid"] == test_id), None)
        if test is None:
            raise ValueError("Test ID not found in the latest SBFL run")
        blocks = test.get("invocations", [])
        return {"run_id": run_id, "nodeid": test_id, "outcome": test["outcome"],
                "failure": test.get("failure"), "excluded_from_ranking": test.get("excluded_from_ranking", False),
                "total_invocations": len(blocks), "invocations": blocks[offset:offset + limit]}
